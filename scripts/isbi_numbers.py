"""Generate paper/numbers.tex from the results files so every number in the manuscript is traceable."""
import json

import numpy as np

import isbi_sacc as I
import blast_stats as bs

OUT = I.OUT


def pct(x):
    return f'{100 * x:.0f}\\%' if x >= .1 or x == 0 else f'{100 * x:.1f}\\%'


def main():
    r = json.loads((OUT / 'results_isbi.json').read_text())
    d = json.loads((OUT / 'results_design_sim.json').read_text())
    rows = json.loads((bs.MD / 'rows.json').read_text())
    blast = [x for x in rows if x['cohort'] == 'blast']
    procs = [json.loads((bs.BP / 'sessions' / x['id'] / 'processing.json').read_text()) for x in blast]
    v = r['exp2_new_session_null']
    N = {}
    N['Nanimals'] = r['n_animals']; N['Nsessions'] = r['n_sessions']; N['Nregions'] = r['n_regions']
    N['Nsham'] = sum(x['group'] == 'Sham' for x in blast); N['Ntenpsi'] = sum(x['group'] == '10psi' for x in blast)
    N['Ntwentypsi'] = sum(x['group'] == '20psi' for x in blast)
    N['ICC'] = f"{r['exp1_session_icc_RAW']['median_icc']:.2f}"; N['ICCnull'] = f"{r['exp1_session_icc_RAW']['null_mean']:.2f}"
    N['ICCp'] = f"{r['exp1_session_icc_RAW']['p_perm']:.3f}"
    N['SDCbefore'] = f"{np.median([p['sdc']['fwd_rev_corr_before'] for p in procs]):.2f}"
    N['SDCafter'] = f"{np.median([p['sdc']['fwd_rev_corr_after_full_warp'] for p in procs]):.2f}"
    N['Motion'] = f"{max(p['motion']['max_translation_mm'] for p in procs):.1f}"
    fa = lambda m: f"{round(v['RAW'][m]['false_alarm_rate_q10'] * v['RAW'][m]['n_test_shams'])}/{v['RAW'][m]['n_test_shams']}"
    N['FAnaive'] = fa('naive'); N['FAsaccm'] = fa('sacc_m'); N['NtestSACCM'] = v['RAW']['sacc_m']['n_test_shams']
    rowsTex = []
    for feat in [f for f in ['RAW', 'RES-A', 'RES-S'] if f in v]:
        for m, lab in [('naive', 'naive'), ('sacc', 'SACC'), ('sacc_m', 'SACC+M')]:
            e = v[feat][m]
            rowsTex.append(f"{feat} & {lab} & {e['P(p<=0.01)']:.3f} & {e['P(p<=0.05)']:.3f} & "
                           f"{round(e['false_alarm_rate_q10'] * e['n_test_shams'])}/{e['n_test_shams']}\\\\")
    N['TableRows'] = '\n'.join(rowsTex)
    pw = r['exp3_power_RAW']
    N['PowerMax'] = pct(max(e['sensitivity_q10'] for m in pw for e in pw[m]))
    N['VoxPowerMax'] = pct(max(e['region_detected_q10'] for e in r['exp3_voxel_comparator_RAW']))
    cell = lambda S, a: next(c for c in d['cells'] if c['S'] == S and c['amp'] == a)
    N['SimSensEighty'] = pct(cell(80, 3)['sensitivity']); N['SimNullTen'] = pct(cell(10, 0)['any_flag_rate'])
    N['SimNullEighty'] = pct(cell(80, 0)['any_flag_rate'])
    rows2, sess, strat, feats, *_ = I.load()
    controls = [i for i, x in enumerate(rows2) if x['group'] == 'Sham']
    cal, _ = I.calibration(feats['RAW'], controls, sess, 'sacc', True)
    mx = sorted(((cal[j].max(), strat[k]) for j, k in enumerate(controls)), reverse=True)
    prone = [m for m, s in mx if s != 'SUBJ_POS_Supine']
    N['MaxProneA'] = f'{prone[0]:.1f}'; N['MaxProneB'] = f'{prone[1]:.1f}'
    N['MaxOther'] = f"{max(m for m, s in mx if s == 'SUBJ_POS_Supine'):.1f}"
    app = r['exp4_application']['RAW/sacc_m']
    blast_keys = [k for k in app['summary'] if 'Sham' not in k]
    N['AppNblast'] = sum(app['summary'][k]['n'] for k in blast_keys)
    N['AppFlagged'] = sum(round(app['summary'][k]['share_any_flag'] * app['summary'][k]['n']) for k in blast_keys)
    mrs = app.get('mrs', {})
    N['MRSrho'] = f"{mrs.get('rho_neglog10p_vs_NAA', float('nan')):.2f}"; N['MRSp'] = f"{mrs.get('p_perm', float('nan')):.2f}"
    N['MRSn'] = mrs.get('n')
    tex = ''.join(f'\\newcommand{{\\{k}}}{{{val}}}\n' for k, val in N.items())
    (OUT / 'paper' / 'numbers.tex').write_text('% generated by scripts/isbi_numbers.py; do not edit\n' + tex)
    print(tex)


if __name__ == '__main__':
    main()
